// Captures real POST /api/analyze results for the built-in sample posts
// and saves them as the fallback shown when the AI service is unavailable.
// Usage: start the app with "npm run dev", then run "npm run capture:samples".
import { writeFile } from "node:fs/promises";
import { SAMPLE_POSTS } from "../src/shared/data/samples.ts";

const API_URL = process.env.CAPTURE_API_URL ?? "http://localhost:3000/api/analyze";
const OUTPUT = new URL("../src/shared/data/sample-results.ts", import.meta.url);
// Spacing requests keeps the capture under the free tier's tokens-per-minute limit
const PAUSE_MS = 20_000;

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

const results = {};

for (const [index, sample] of SAMPLE_POSTS.entries()) {
    if (index > 0) {
        console.log(`Waiting ${PAUSE_MS / 1000}s to stay under the rate limit...`);
        await sleep(PAUSE_MS);
    }

    process.stdout.write(`Capturing "${sample.id}"... `);

    const res = await fetch(API_URL, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ mode: "text", text: sample.text, context: sample.context }),
    });
    const body = await res.json().catch(() => null);

    if (!res.ok || !body?.report) {
        console.error(`failed (HTTP ${res.status}): ${JSON.stringify(body)}`);
        process.exit(1);
    }

    results[sample.id] = body.report;
    console.log(`ok (next move: ${body.report.nextMove})`);
}

const capturedAt = new Date().toISOString();

const file = `// Generated by scripts/capture-sample-results.mjs from real runs of POST /api/analyze.
// Do not edit by hand. Run "npm run capture:samples" with the dev server running to refresh.
import type { SamplePost } from "@/shared/data/samples";
import type { ProcessedReport } from "@/shared/types";

export const SAMPLE_RESULTS_CAPTURED_AT = ${JSON.stringify(capturedAt)};

export const SAMPLE_RESULTS: Record<SamplePost["id"], ProcessedReport> = ${JSON.stringify(results, null, 2)};
`;

await writeFile(OUTPUT, file, "utf8");
console.log(`Saved ${Object.keys(results).length} results to src/shared/data/sample-results.ts`);